@dataclass(slots=True)
class MonthView:
    span: PeriodSpan
    rows: list[Row]
    income_entries: list[IncomeEntry]
    occurrences: list[rec.Occurrence]
    spending: Spending
    late: list[tuple[Receipt, BudgetPeriod]]


async def month_view(session: AsyncSession, span: PeriodSpan, today: date) -> MonthView:
    month = span.period.month
    locked = await locked_months(session)
    lines = await all_lines(session)
    history = await _amount_rows(session)
    spent = await spending(session, span.start, span.end, [line for line in lines if line.active])
    last = await rec.last_amounts(session)

    rows: list[Row] = []
    for line in lines:
        plan, _ = line_plan(line, history.get(line.id, []), month, locked)
        pieces = spent.by_line.get(line.id, [])
        if not line.active and not plan and not pieces:
            continue
        tracked = bool(line.category_ids)
        rows.append(Row(
            key=f"line:{line.id}", type="line", id=line.id, name=line.name,
            owner_id=line.owner_id, kind=line.kind, plan=plan,
            actual=_q(sum((p.amount for p in pieces), ZERO)) if tracked else None,
            active=line.active, category_ids=line.category_ids, pieces=pieces,
        ))

    payments = (
        await session.scalars(
            select(RecurringPayment)
            .where(RecurringPayment.direction == Direction.EXPENSE.value)
            .order_by(RecurringPayment.name)
        )
    ).all()
    for payment in payments:
        plan = recurring_plan(payment, month, last)
        pieces = spent.by_recurring.get(payment.id, [])
        if not plan and not pieces:
            continue
        rows.append(Row(
            key=f"recurring:{payment.id}", type="recurring", id=payment.id, name=payment.name,
            owner_id=payment.owner_id,
            kind=(
                BudgetLineKind.VARIABLE.value
                if payment.amount_mode == AmountMode.VARIABLE.value
                else BudgetLineKind.FIX.value
            ),
            plan=plan, actual=_q(sum((p.amount for p in pieces), ZERO)),
            yearly=payment.cadence == Cadence.YEARLY.value, active=payment.active,
            category_ids=[payment.category_id] if payment.category_id else [], pieces=pieces,
        ))

    for owner, pieces in spent.unplanned.items():
        rows.append(Row(
            key=f"unplanned:{owner or 'kozos'}", type="unplanned", name="Tervezetlen",
            owner_id=owner, kind=BudgetLineKind.VARIABLE.value,
            actual=_q(sum((p.amount for p in pieces), ZERO)), pieces=pieces,
        ))

    income_stmt = select(IncomeEntry).where(IncomeEntry.received_on >= span.start)
    if span.end is not None:
        income_stmt = income_stmt.where(IncomeEntry.received_on < span.end)
    income_entries = list(
        (await session.scalars(income_stmt.order_by(IncomeEntry.received_on))).all()
    )
    occurrences = await rec.occurrences_between(
        session, span.start, span.expectation_end(today), today
    )
    return MonthView(
        span=span, rows=rows, income_entries=income_entries, occurrences=occurrences,
        spending=spent, late=await late_receipts(session, span),
    )


async def late_receipts(
    session: AsyncSession, span: PeriodSpan
) -> list[tuple[Receipt, BudgetPeriod]]:
    """Receipts entered after the meeting that closed the period they are dated in.

    For a closed period: the ones entered after it closed. For the current one: those that
    turned up for any earlier period since this one began - the next meeting's business.
    """
    spans = await periods(session)
    closed = [s for s in spans if s.period.closed_at is not None]
    if span.is_current:
        candidates = [s for s in closed if s.end is not None and s.end <= span.start]
        since = span.period.created_at
    else:
        candidates = [span] if span.period.closed_at is not None else []
        since = None

    out: list[tuple[Receipt, BudgetPeriod]] = []
    for candidate in candidates:
        cutoff = candidate.period.closed_at
        if since is not None and since > cutoff:
            cutoff = since
        stmt = _range_filter(
            select(Receipt).where(Receipt.created_at > cutoff), candidate.start, candidate.end
        )
        for receipt in (await session.scalars(stmt.order_by(Receipt.purchased_at))).all():
            out.append((receipt, candidate.period))
    return out


@dataclass(slots=True)
class PlanRow:
    key: str
    type: str                  # line | recurring | income
    id: uuid.UUID
    name: str
    owner_id: uuid.UUID | None
    kind: str
    active: bool
    category_ids: list[uuid.UUID]
    amounts: list[tuple[Decimal, bool]]  # per month: amount, set in that very month
    yearly: bool = False
    default_shares: list | None = None


@dataclass(slots=True)
class PlanMonth:
    month: date
    period_id: uuid.UUID | None
    locked: bool


@dataclass(slots=True)
class PlanGrid:
    months: list[PlanMonth]
    rows: list[PlanRow]


async def plan_grid(session: AsyncSession, start: date, count: int) -> PlanGrid:
    months = [add_months(first_of(start), i) for i in range(count)]
    locked = await locked_months(session)
    by_month = {
        p.month: p.id for p in (await session.scalars(select(BudgetPeriod))).all()
    }
    history = await _amount_rows(session)
    last = await rec.last_amounts(session)

    rows: list[PlanRow] = []
    for line in await all_lines(session):
        rows.append(PlanRow(
            key=f"line:{line.id}", type="line", id=line.id, name=line.name,
            owner_id=line.owner_id, kind=line.kind, active=line.active,
            category_ids=line.category_ids,
            amounts=[line_plan(line, history.get(line.id, []), m, locked) for m in months],
        ))
    for payment in (
        await session.scalars(select(RecurringPayment).order_by(RecurringPayment.name))
    ).all():
        amounts = [(recurring_plan(payment, m, last), False) for m in months]
        if not any(amount for amount, _ in amounts):
            continue
        income = payment.direction == Direction.INCOME.value
        rows.append(PlanRow(
            key=f"{'income' if income else 'recurring'}:{payment.id}",
            type="income" if income else "recurring",
            id=payment.id, name=payment.name, owner_id=payment.owner_id,
            kind=(
                BudgetLineKind.VARIABLE.value
                if payment.amount_mode == AmountMode.VARIABLE.value
                else BudgetLineKind.FIX.value
            ),
            active=payment.active,
            category_ids=[payment.category_id] if payment.category_id else [],
            amounts=amounts, yearly=payment.cadence == Cadence.YEARLY.value,
            default_shares=payment.default_shares,
        ))
    return PlanGrid(
        months=[PlanMonth(m, by_month.get(m), m in locked) for m in months], rows=rows
    )


@dataclass(slots=True)
class Totals:
    income: Decimal = ZERO
    planned: Decimal = ZERO

    @property
    def free(self) -> Decimal:
        return self.income - self.planned


def plan_totals(
    grid: PlanGrid, people: list[uuid.UUID]
) -> list[tuple[Totals, dict[uuid.UUID, Totals]]]:
    """Per month: the household's income, plan and what is left free, and each person's.

    A person's share of the Közös plan follows `owner_shares`; so does a Közös income,
    which is rare but possible (a refund to the household).
    """
    out: list[tuple[Totals, dict[uuid.UUID, Totals]]] = []
    for index in range(len(grid.months)):
        house = Totals()
        each: dict[uuid.UUID, Totals] = {person: Totals() for person in people}
        for row in grid.rows:
            amount = row.amounts[index][0]
            if not amount:
                continue
            shares = owner_shares(
                row.owner_id, people, row.default_shares if row.type != "line" else None
            )
            for person, share in shares.items():
                bucket = each.setdefault(person, Totals())
                if row.type == "income":
                    bucket.income += _q(amount * share)
                else:
                    bucket.planned += _q(amount * share)
            if row.type == "income":
                house.income += amount
            else:
                house.planned += amount
        out.append((house, each))
    return out
