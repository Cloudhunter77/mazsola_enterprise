"""The plan, and how the money actually went against it.

Three questions drive everything here.

**Which period?** A period starts at a monthly meeting and ends where the next one starts.
Receipts and income belong to a period by their date, so a receipt typed in after the
meeting still lands in the period it was spent in - flagged, so the next meeting sees it.

**Which line?** Every receipt line counts against the budget line of its category, and
whose line depends on the split: a split receipt is shared spending and counts in full
against the Közös lines, an unsplit one against its payer's. If the category has no line
for that owner, its parent category's line is tried, and so on up the tree - a budget on
Élelmiszer covers Tejtermék. Spending that finds no line at all is *tervezetlen*, shown per
owner rather than dropped, because unplanned spending is exactly what a budget meeting is
for. A bill generated by a Rendszeres item counts against that item's own row instead, so
the rent is never planned or spent twice.

**How much?** A line's amount carries forward from the last month it was set until changed,
as in the spreadsheet this replaces. Closing a period writes its amounts down explicitly, so
editing an earlier month can never change a month that was already discussed.

Nothing here is stored as a running total. Like the balance in Elszámolás, every figure is
computed from the receipts each time, so recategorising or re-splitting a receipt later
simply moves it to the right line.
"""

