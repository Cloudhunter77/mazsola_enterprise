ZERO = Decimal("0.00")
CENT = Decimal("0.01")
UNCATEGORISED_SLUG = "besorolatlan"
# Lines of a receipt that are things paid for. Discounts and rounding are not lines of their
# own here: they are spread over these in proportion, so the lines add up to the total.
PAID_LINE_KINDS = (LineKind.ITEM.value, LineKind.FEE.value, LineKind.DEPOSIT.value)

HU_MONTHS = (
    "január", "február", "március", "április", "május", "június",
    "július", "augusztus", "szeptember", "október", "november", "december",
)


class BudgetError(ValueError):
    """A request the plan cannot honour; the message is for the screen."""


def today_local() -> date:
    return datetime.now(LOCAL_TZ).date()


def first_of(day: date) -> date:
    return day.replace(day=1)


def add_months(month: date, count: int) -> date:
    index = month.year * 12 + month.month - 1 + count
    return date(index // 12, index % 12 + 1, 1)


def month_name(month: date) -> str:
    return f"{month.year}. {HU_MONTHS[month.month - 1]}"


def _q(value: Decimal | int | float | None) -> Decimal:
    return (Decimal(value) if value is not None else ZERO).quantize(CENT, rounding=ROUND_HALF_UP)


# --- periods -------------------------------------------------------------------


@dataclass(slots=True)
class PeriodSpan:
    period: BudgetPeriod
    start: date
    # Exclusive. None for the newest period, which runs until the next meeting.
    end: date | None

    @property
    def is_current(self) -> bool:
        return self.end is None

    def expectation_end(self, today: date) -> date:
        """Where to stop looking for what this period is still expecting.

        A closed period ends where the next began. The current one has no end yet, so it
        expects what falls due up to the end of the month it plans - or up to today, if the
        meeting is running late and bills of the following month have already arrived.
        """
        if self.end is not None:
            return self.end
        return max(add_months(self.period.month, 1), today + timedelta(days=1))


async def periods(session: AsyncSession) -> list[PeriodSpan]:
    rows = (
        await session.scalars(select(BudgetPeriod).order_by(BudgetPeriod.starts_on))
    ).all()
    return [
        PeriodSpan(period, period.starts_on, rows[i + 1].starts_on if i + 1 < len(rows) else None)
        for i, period in enumerate(rows)
    ]


def span_of(spans: list[PeriodSpan], period_id: uuid.UUID | None) -> PeriodSpan | None:
    if not spans:
        return None
    if period_id is None:
        return spans[-1]
    return next((span for span in spans if span.period.id == period_id), None)


def span_for_day(spans: list[PeriodSpan], day: date) -> PeriodSpan | None:
    for span in spans:
        if span.start <= day and (span.end is None or day < span.end):
            return span
    return None


def meeting_due(spans: list[PeriodSpan], today: date) -> bool:
    """From the 1st of a month until the meeting that plans it has happened.

    A meeting held on 30 October that already planned November counts: the question is
    whether this month has been planned, not on which day of it you sat down.
    """
    if not spans:
        return True
    return max(span.period.month for span in spans) < first_of(today)


def suggested_month(starts_on: date, previous: BudgetPeriod | None) -> date:
    """The month a meeting on `starts_on` plans, unless you say otherwise.

    Early in a month you plan that month; in the last third you are already planning the
    next. Never a month that already has a period.
    """
    month = first_of(starts_on) if starts_on.day <= 20 else add_months(first_of(starts_on), 1)
    if previous is not None and month <= previous.month:
        month = add_months(previous.month, 1)
    return month


async def locked_months(session: AsyncSession) -> set[date]:
    return set(
        (
            await session.scalars(
                select(BudgetPeriod.month).where(BudgetPeriod.closed_at.is_not(None))
            )
        ).all()
    )


async def open_period(
    session: AsyncSession,
    *,
    starts_on: date,
    month: date | None,
    user_id: uuid.UUID | None,
    today: date,
) -> BudgetPeriod:
    """The end of a meeting: close the period that was running and start the next one."""
    spans = await periods(session)
    latest = spans[-1].period if spans else None
    if starts_on > today:
        raise BudgetError("A megbeszélés dátuma nem lehet a jövőben.")
    month = first_of(month) if month is not None else suggested_month(starts_on, latest)
    if latest is not None:
        if starts_on <= latest.starts_on:
            raise BudgetError(
                f"Az új időszak csak az előző kezdete ({latest.starts_on.isoformat()}) "
                "után indulhat."
            )
        if month <= latest.month:
            raise BudgetError(
                f"Az új időszaknak {month_name(latest.month)} utáni hónapot kell terveznie."
            )
        await close_period(session, latest, user_id)

    period = BudgetPeriod(month=month, starts_on=starts_on, opened_by_id=user_id)
    session.add(period)
    await session.flush()
    return period


async def close_period(
    session: AsyncSession, period: BudgetPeriod, user_id: uuid.UUID | None
) -> None:
    if period.closed_at is not None:
        return
    await _write_down_plan(session, period.month)
    period.closed_at = datetime.now(UTC)
    period.closed_by_id = user_id
    await session.flush()


async def reopen_period(session: AsyncSession, period: BudgetPeriod) -> None:
    period.closed_at = None
    period.closed_by_id = None
    await session.flush()


async def _write_down_plan(session: AsyncSession, month: date) -> None:
    """Store every line's amount for `month` explicitly, as the plan stood when closed.

    Amounts carry forward, so a month that only inherits its value would change whenever an
    earlier month is edited. An archived line plans nothing in an open month; writing that
    down as 0 keeps it at 0 after the month is closed, rather than letting the value it had
    before it was archived reappear.
    """
    rows = await _amount_rows(session)
    for line in (await session.scalars(select(BudgetLine))).all():
        history = rows.get(line.id, [])
        if any(m == month for m, _ in history):
            if not line.active:
                await session.execute(
                    delete(Budget).where(Budget.line_id == line.id).where(Budget.month == month)
                )
                session.add(Budget(line_id=line.id, month=month, amount=ZERO))
            continue
        amount, _ = _effective(history, month)
        if not line.active:
            amount = ZERO
        if amount or history:
            session.add(Budget(line_id=line.id, month=month, amount=amount))
    await session.flush()


# --- plan amounts ----------------------------------------------------------------


async def _amount_rows(session: AsyncSession) -> dict[uuid.UUID, list[tuple[date, Decimal]]]:
    rows: dict[uuid.UUID, list[tuple[date, Decimal]]] = defaultdict(list)
    for line_id, month, amount in (
        await session.execute(
            select(Budget.line_id, Budget.month, Budget.amount).order_by(Budget.month)
        )
    ).all():
        rows[line_id].append((month, Decimal(amount)))
    return rows


def _effective(history: list[tuple[date, Decimal]], month: date) -> tuple[Decimal, bool]:
    """The amount in force in `month`, and whether it was set in that very month."""
    amount, explicit = ZERO, False
    for set_in, value in history:
        if set_in > month:
            break
        amount, explicit = value, set_in == month
    return amount, explicit


def line_plan(
    line: BudgetLine,
    history: list[tuple[date, Decimal]],
    month: date,
    locked: set[date],
) -> tuple[Decimal, bool]:
    if month not in locked and not line.active:
        return ZERO, False
    return _effective(history, month)


async def set_amount(
    session: AsyncSession, line: BudgetLine, month: date, amount: Decimal | None
) -> None:
    """Set a line's amount from `month` on. None removes the change, inheriting again."""
    month = first_of(month)
    if month in await locked_months(session):
        raise BudgetError(
            f"{month_name(month)} le van zárva. Nyisd újra az időszakát, ha javítani kell."
        )
    if amount is not None and amount < 0:
        raise BudgetError("A keret nem lehet negatív.")
    existing = await session.scalar(
        select(Budget).where(Budget.line_id == line.id).where(Budget.month == month)
    )
    if amount is None:
        if existing is not None:
            await session.delete(existing)
    elif existing is not None:
        existing.amount = _q(amount)
    else:
        session.add(Budget(line_id=line.id, month=month, amount=_q(amount)))
    await session.flush()


# --- lines -------------------------------------------------------------------------


async def check_line(
    session: AsyncSession,
    *,
    line_id: uuid.UUID | None,
    owner_id: uuid.UUID | None,
    kind: str,
    category_ids: list[uuid.UUID],
) -> None:
    """A category may be in only one active line per owner, or spending would be ambiguous."""
    if kind not in {k.value for k in BudgetLineKind}:
        raise BudgetError("Ismeretlen csoport.")
    if owner_id is not None and await session.get(User, owner_id) is None:
        raise BudgetError("Nincs ilyen felhasználó.")
    if kind in SPENDING_KINDS and not category_ids:
        raise BudgetError("Egy fix vagy változó keretnek legalább egy kategória kell.")
    if not category_ids:
        return
    known = {
        c.id: c.name
        for c in (
            await session.scalars(select(Category).where(Category.id.in_(category_ids)))
        ).all()
    }
    if len(known) != len(set(category_ids)):
        raise BudgetError("Nincs ilyen kategória.")
    clash_stmt = (
        select(BudgetLine.name, BudgetLineCategory.category_id)
        .join(BudgetLineCategory, BudgetLineCategory.line_id == BudgetLine.id)
        .where(BudgetLine.active.is_(True))
        .where(BudgetLineCategory.category_id.in_(category_ids))
        .where(
            BudgetLine.owner_id == owner_id if owner_id is not None
            else BudgetLine.owner_id.is_(None)
        )
    )
    if line_id is not None:
        clash_stmt = clash_stmt.where(BudgetLine.id != line_id)
    clash = (await session.execute(clash_stmt)).first()
    if clash is not None:
        raise BudgetError(f"A(z) {known[clash[1]]} kategória már a(z) {clash[0]} sorban van.")


async def set_line_categories(
    session: AsyncSession, line: BudgetLine, category_ids: list[uuid.UUID]
) -> None:
    wanted = list(dict.fromkeys(category_ids))
    # A line created a moment ago has never had its categories loaded, and an async session
    # cannot load them implicitly on first touch.
    await session.refresh(line, attribute_names=["categories"])
    line.categories = [
        link for link in line.categories if link.category_id in wanted
    ] + [
        BudgetLineCategory(category_id=category_id)
        for category_id in wanted
        if category_id not in line.category_ids
    ]
    await session.flush()


async def remove_line(session: AsyncSession, line: BudgetLine) -> bool:
    """Delete a line, or archive it if a closed period already planned with it.

    Returns True when it was deleted, False when archived. A line that a discussed month
    was planned with is part of that month's record; deleting it would rewrite history.
    """
    last_close = await session.scalar(select(func.max(BudgetPeriod.closed_at)))
    if last_close is not None and line.created_at is not None and line.created_at <= last_close:
        line.active = False
        await session.flush()
        return False
    await session.delete(line)
    await session.flush()
    return True


# --- spending against lines ---------------------------------------------------------


@dataclass(slots=True)
class Piece:
    """Part of one receipt that counts against one row."""

    receipt_id: uuid.UUID
    day: date
    merchant: str | None
    amount: Decimal
    category_id: uuid.UUID | None = None


@dataclass(slots=True)
class Row:
    """One row of Hónap: a budget line, a recurring bill, or what nothing planned."""

    key: str
    type: str                       # line | recurring | unplanned
    name: str
    owner_id: uuid.UUID | None
    kind: str
    plan: Decimal = ZERO
    actual: Decimal | None = ZERO   # None: money set aside, which no receipt represents
    id: uuid.UUID | None = None
    yearly: bool = False
    active: bool = True
    category_ids: list[uuid.UUID] = field(default_factory=list)
    pieces: list[Piece] = field(default_factory=list)


@dataclass(slots=True)
class Spending:
    """Where every forint of a period went."""

    by_line: dict[uuid.UUID, list[Piece]] = field(default_factory=lambda: defaultdict(list))
    by_recurring: dict[uuid.UUID, list[Piece]] = field(
        default_factory=lambda: defaultdict(list)
    )
    unplanned: dict[uuid.UUID | None, list[Piece]] = field(
        default_factory=lambda: defaultdict(list)
    )
    # Receipts with a line nobody categorised yet, each with its whole total.
    uncategorised: dict[uuid.UUID, Piece] = field(default_factory=dict)
    # Unsplit receipts whose spending found no line of the payer, though a Közös line covers
    # it: most likely a shared bill nobody split.
    maybe_shared: dict[uuid.UUID, Piece] = field(default_factory=dict)
    receipt_count: int = 0


def _range_filter(stmt, start: date, end: date | None):
    stmt = stmt.where(Receipt.status.in_(COUNTED_STATUSES))
    stmt = stmt.where(Receipt.purchased_at >= local_day_start(start))
    if end is not None:
        stmt = stmt.where(Receipt.purchased_at < local_day_start(end))
    return stmt


def allocate(total: Decimal | None, lines: list[tuple[Decimal, uuid.UUID | None]]) -> list[
    tuple[Decimal, uuid.UUID | None]
]:
    """Spread a receipt's total over its paid lines in proportion to what each cost.

    Discounts and cash rounding are part of what you paid but belong to no line, so each
    line takes its share of them. The parts are rounded to the fillér and the last one takes
    the remainder, so they always add up to exactly the total.
    """
    paid = sum((amount for amount, _ in lines if amount > 0), ZERO)
    total = _q(total) if total is not None else _q(paid)
    if paid <= 0 or not lines:
        return [(total, None)]
    out: list[tuple[Decimal, uuid.UUID | None]] = []
    running = ZERO
    positive = [(amount, category) for amount, category in lines if amount > 0]
    for index, (amount, category) in enumerate(positive):
        if index == len(positive) - 1:
            part = total - running
        else:
            part = _q(total * amount / paid)
            running += part
        out.append((part, category))
    return out


async def spending(
    session: AsyncSession, start: date, end: date | None, lines: list[BudgetLine]
) -> Spending:
    categories = (await session.scalars(select(Category))).all()
    parent = {c.id: c.parent_id for c in categories}
    blank = {c.id for c in categories if c.slug == UNCATEGORISED_SLUG}

    index: dict[tuple[uuid.UUID | None, uuid.UUID], BudgetLine] = {}
    kozos_categories: set[uuid.UUID] = set()
    for line in lines:
        for category_id in line.category_ids:
            index[(line.owner_id, category_id)] = line
            if line.owner_id is None:
                kozos_categories.add(category_id)

    def match(owner: uuid.UUID | None, category: uuid.UUID | None) -> BudgetLine | None:
        while category is not None:
            line = index.get((owner, category))
            if line is not None:
                return line
            category = parent.get(category)
        return None

    def covered_by_kozos(category: uuid.UUID | None) -> bool:
        while category is not None:
            if category in kozos_categories:
                return True
            category = parent.get(category)
        return False

    receipts = (
        await session.execute(
            _range_filter(
                select(Receipt, Merchant.name)
                .outerjoin(Merchant, Merchant.id == Receipt.merchant_id)
                .options(selectinload(Receipt.items)),
                start,
                end,
            ).order_by(Receipt.purchased_at)
        )
    ).all()
    ids = [receipt.id for receipt, _ in receipts]
    split_ids = set(
        (
            await session.scalars(
                select(ReceiptShare.receipt_id).where(ReceiptShare.receipt_id.in_(ids)).distinct()
            )
        ).all()
    ) if ids else set()
    generated_by = dict(
        (
            await session.execute(
                select(RecurringCharge.receipt_id, RecurringCharge.recurring_id)
                .where(RecurringCharge.receipt_id.in_(ids))
            )
        ).all()
    ) if ids else {}

    out = Spending(receipt_count=len(receipts))
    for receipt, merchant_name in receipts:
        day = receipt.purchased_at.astimezone(LOCAL_TZ).date()
        merchant = merchant_name or receipt.merchant_raw_name

        if receipt.id in generated_by:
            out.by_recurring[generated_by[receipt.id]].append(
                Piece(receipt.id, day, merchant, _q(receipt.total_gross))
            )
            continue

        owner = None if receipt.id in split_ids else receipt.paid_by_id
        paid_lines = [
            (
                Decimal(item.gross_amount or 0),
                None if item.category_id in blank else item.category_id,
            )
            for item in receipt.items
            if item.kind in PAID_LINE_KINDS
        ]
        if any(category is None for _, category in paid_lines) or not paid_lines:
            out.uncategorised[receipt.id] = Piece(
                receipt.id, day, merchant, _q(receipt.total_gross)
            )

        # One piece per (row, category) per receipt, so a long grocery receipt reads as
        # one entry under Kaja, not thirty.
        parts: dict[tuple[str, uuid.UUID | None, uuid.UUID | None], Decimal] = defaultdict(
            lambda: ZERO
        )
        for amount, category in allocate(receipt.total_gross, paid_lines):
            line = match(owner, category)
            if line is not None:
                parts[("line", line.id, None)] += amount
            else:
                parts[("unplanned", owner, category)] += amount
                if owner is not None and covered_by_kozos(category):
                    flagged = out.maybe_shared.setdefault(
                        receipt.id, Piece(receipt.id, day, merchant, ZERO)
                    )
                    flagged.amount += amount
        for (kind, key, category), amount in parts.items():
            if kind == "line":
                out.by_line[key].append(Piece(receipt.id, day, merchant, amount))
            else:
                out.unplanned[key].append(Piece(receipt.id, day, merchant, amount, category))
    return out


# --- recurring rows --------------------------------------------------------------------


def _active_in(payment: RecurringPayment, month: date) -> bool:
    if not payment.active:
        return False
    if first_of(payment.starts_on) > month:
        return False
    return payment.ends_on is None or payment.ends_on >= month


def recurring_plan(
    payment: RecurringPayment, month: date, last: dict[uuid.UUID, Decimal]
) -> Decimal:
    """What a recurring item puts into one month's plan. A yearly one: a twelfth of it."""
    if not _active_in(payment, month):
        return ZERO
    amount = rec.expected_amount(payment, last)
    if payment.cadence == Cadence.YEARLY.value:
        return _q(amount / 12)
    return _q(amount)


def owner_shares(
    owner_id: uuid.UUID | None,
    people: list[uuid.UUID],
    default_shares: list | None = None,
) -> dict[uuid.UUID, Decimal]:
    """How an owner's amount divides between people in the per-person view.

    A person's own line is all theirs. A Közös one divides equally - the spreadsheet's
    "Egyenlő" contribution - unless it is a recurring item that says how it is split.
    """
    if owner_id is not None:
        return {owner_id: Decimal(1)}
    if default_shares:
        return {
            uuid.UUID(str(share["user_id"])): Decimal(str(share["percent"])) / 100
            for share in default_shares
        }
    if not people:
        return {}
    return {person: Decimal(1) / len(people) for person in people}


