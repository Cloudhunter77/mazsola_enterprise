@dataclass(slots=True)
class PeriodSpan:
    period: BudgetPeriod
    start: date
    # Exclusive. None for the newest period, which runs until the next meeting.
    end: date | None

    @property
    def is_current(self) -> bool:
        return self.end is None

    def expectation_end(self, today: date) -> date:
        """Where to stop looking for what this period is still expecting.

        A closed period ends where the next began. The current one has no end yet, so it
        expects what falls due up to the end of the month it plans - or up to today, if the
        meeting is running late and bills of the following month have already arrived.
        """
        if self.end is not None:
            return self.end
        return max(add_months(self.period.month, 1), today + timedelta(days=1))


async def periods(session: AsyncSession) -> list[PeriodSpan]:
    rows = (
        await session.scalars(select(BudgetPeriod).order_by(BudgetPeriod.starts_on))
    ).all()
    return [
        PeriodSpan(period, period.starts_on, rows[i + 1].starts_on if i + 1 < len(rows) else None)
        for i, period in enumerate(rows)
    ]


def span_of(spans: list[PeriodSpan], period_id: uuid.UUID | None) -> PeriodSpan | None:
    if not spans:
        return None
    if period_id is None:
        return spans[-1]
    return next((span for span in spans if span.period.id == period_id), None)


def span_for_day(spans: list[PeriodSpan], day: date) -> PeriodSpan | None:
    for span in spans:
        if span.start <= day and (span.end is None or day < span.end):
            return span
    return None


def meeting_due(spans: list[PeriodSpan], today: date) -> bool:
    """From the 1st of a month until the meeting that plans it has happened.

    A meeting held on 30 October that already planned November counts: the question is
    whether this month has been planned, not on which day of it you sat down.
    """
    if not spans:
        return True
    return max(span.period.month for span in spans) < first_of(today)


def suggested_month(starts_on: date, previous: BudgetPeriod | None) -> date:
    """The month a meeting on `starts_on` plans, unless you say otherwise.

    Early in a month you plan that month; in the last third you are already planning the
    next. Never a month that already has a period.
    """
    month = first_of(starts_on) if starts_on.day <= 20 else add_months(first_of(starts_on), 1)
    if previous is not None and month <= previous.month:
        month = add_months(previous.month, 1)
    return month


async def locked_months(session: AsyncSession) -> set[date]:
    return set(
        (
            await session.scalars(
                select(BudgetPeriod.month).where(BudgetPeriod.closed_at.is_not(None))
            )
        ).all()
    )


async def open_period(
    session: AsyncSession,
    *,
    starts_on: date,
    month: date | None,
    user_id: uuid.UUID | None,
    today: date,
    transfers: list[TransferIn] | None = None,
    checks: list[tuple[uuid.UUID, Decimal]] | None = None,
) -> BudgetPeriod:
    """The end of a meeting: close the period that was running and start the next one.

    The meeting's transfer checklist (D28) and the pocket balances read off Revolut are
    recorded with it, dated the day the new period starts.
    """
    spans = await periods(session)
    latest = spans[-1].period if spans else None
    if starts_on > today:
        raise BudgetError("A megbeszélés dátuma nem lehet a jövőben.")
    month = first_of(month) if month is not None else suggested_month(starts_on, latest)
    if latest is not None:
        if starts_on <= latest.starts_on:
            raise BudgetError(
                f"Az új időszak csak az előző kezdete ({latest.starts_on.isoformat()}) "
                "után indulhat."
            )
        if month <= latest.month:
            raise BudgetError(
                f"Az új időszaknak {month_name(latest.month)} utáni hónapot kell terveznie."
            )
        await close_period(session, latest, user_id)

    period = BudgetPeriod(month=month, starts_on=starts_on, opened_by_id=user_id)
    session.add(period)
    await session.flush()
    for transfer in transfers or []:
        await _plan_transfer(session, period, transfer, user_id)
    for pocket_id, balance in checks or []:
        await record_check(session, pocket_id, balance, starts_on, user_id, period.id)
    return period


@dataclass(slots=True)
class ProposedTransfer:
    """One line of the meeting's checklist: who sends how much into which pocket."""

    line: BudgetLine
    pocket: Pocket
    from_user_id: uuid.UUID | None
    amount: Decimal
    done: bool = True


async def proposed_transfers(
    session: AsyncSession, month: date, people: list[uuid.UUID]
) -> list[ProposedTransfer]:
    """What each person sends into which pocket for `month` (D28).

    Every pocket line's planned amount, divided the way the per-person view divides it: a
    person's own line is theirs to fund, a Közös one is split equally (D19).
    """
    locked = await locked_months(session)
    history = await _amount_rows(session)
    pockets = {p.id: p for p in (await session.scalars(select(Pocket))).all()}
    out: list[ProposedTransfer] = []
    for line in await all_lines(session):
        if line.pocket_id is None or not line.active or line.pocket_id not in pockets:
            continue
        amount, _ = line_plan(line, history.get(line.id, []), month, locked)
        if amount <= 0:
            continue
        shares = owner_shares(line.owner_id, people)
        parts = [(person, _q(amount * share)) for person, share in shares.items()]
        if parts:
            # The rounding goes to the last person, so the parts add up to the plan.
            parts[-1] = (parts[-1][0], amount - sum((a for _, a in parts[:-1]), ZERO))
        for person, part in parts:
            if part > 0:
                out.append(ProposedTransfer(line, pockets[line.pocket_id], person, part))
    return out


@dataclass(slots=True)
class TransferIn:
    line_id: uuid.UUID
    from_user_id: uuid.UUID | None
    amount: Decimal
    done: bool


async def _plan_transfer(
    session: AsyncSession, period: BudgetPeriod, transfer: TransferIn, user_id
) -> None:
    line = await session.get(BudgetLine, transfer.line_id)
    if line is None or line.pocket_id is None:
        raise BudgetError("Egy átutalás olyan sorra mutat, ami nincs zsebben.")
    if transfer.amount <= 0:
        return
    session.add(PocketTransfer(
        pocket_id=line.pocket_id, line_id=line.id, amount=_q(transfer.amount),
        on=period.starts_on, kind="plan", done=transfer.done,
        done_at=datetime.now(UTC) if transfer.done else None,
        from_user_id=transfer.from_user_id, period_id=period.id,
    ))
    await session.flush()


async def record_check(
    session: AsyncSession,
    pocket_id: uuid.UUID,
    balance: Decimal,
    on: date,
    user_id,
    period_id: uuid.UUID | None = None,
) -> PocketCheck:
    """What Revolut showed in a pocket on a day (D28). At a meeting it is read before that
    meeting's transfers are sent, which `period_id` records."""
    if await session.get(Pocket, pocket_id) is None:
        raise BudgetError("Nincs ilyen zseb.")
    check = PocketCheck(
        pocket_id=pocket_id, balance=_q(balance), checked_on=on, created_by_id=user_id,
        period_id=period_id,
    )
    session.add(check)
    await session.flush()
    return check


async def mark_transfer_done(
    session: AsyncSession, transfer: PocketTransfer, on: date
) -> None:
    """A planned transfer was actually sent. It counts from the day it was sent."""
    transfer.done = True
    transfer.done_at = datetime.now(UTC)
    transfer.on = max(transfer.on, on) if transfer.kind == "plan" else transfer.on
    await session.flush()


async def move_money(
    session: AsyncSession,
    *,
    pocket_id: uuid.UUID,
    from_line: uuid.UUID | None,
    to_line: uuid.UUID | None,
    amount: Decimal,
    on: date,
    kind: str = "move",
    note: str | None = None,
) -> None:
    """Move money between two buckets of the same pocket, or between earmarks of two."""
    if amount <= 0:
        raise BudgetError("Az összegnek nullánál nagyobbnak kell lennie.")
    group = uuid.uuid4()
    target_pocket = pocket_id
    if to_line is not None:
        target = await session.get(BudgetLine, to_line)
        if target is None or target.pocket_id is None:
            raise BudgetError("A cél nincs zsebben.")
        target_pocket = target.pocket_id
    session.add(PocketTransfer(pocket_id=pocket_id, line_id=from_line, amount=-_q(amount),
                               on=on, kind=kind, group_id=group, note=note))
    session.add(PocketTransfer(pocket_id=target_pocket, line_id=to_line, amount=_q(amount),
                               on=on, kind=kind, group_id=group, note=note))
    await session.flush()


async def settle_goal(
    session: AsyncSession,
    line: BudgetLine,
    *,
    today: date,
    move_to: uuid.UUID | None = None,
    release: bool = False,
) -> Decimal:
    """Mark a goal's thing as bought, and deal with what is left in it (D26).

    The leftover moves to another earmark, or is released back to the main account, or -
    with neither - stays in the pocket as unassigned money, so it is never silently lost.
    Returns the leftover that was dealt with.
    """
    if line.pocket_id is None:
        raise BudgetError("Ez nem zsebes cél.")
    led = await pk.ledger(session)
    leftover = led.balance((line.pocket_id, line.id))
    if leftover > 0:
        if release:
            session.add(PocketTransfer(
                pocket_id=line.pocket_id, line_id=line.id, amount=-leftover, on=today,
                kind="release", note=f"{line.name}: maradék visszautalva",
            ))
        else:
            await move_money(
                session, pocket_id=line.pocket_id, from_line=line.id, to_line=move_to,
                amount=leftover, on=today, note=f"{line.name}: maradék",
            )
    line.bought_on = today
    line.active = False
    await session.flush()
    return leftover if leftover > 0 else ZERO


async def close_period(
    session: AsyncSession, period: BudgetPeriod, user_id: uuid.UUID | None
) -> None:
    if period.closed_at is not None:
        return
    await _write_down_plan(session, period.month)
    period.closed_at = datetime.now(UTC)
    period.closed_by_id = user_id
    await session.flush()


async def reopen_period(session: AsyncSession, period: BudgetPeriod) -> None:
    period.closed_at = None
    period.closed_by_id = None
    await session.flush()


async def _write_down_plan(session: AsyncSession, month: date) -> None:
    """Store every line's amount for `month` explicitly, as the plan stood when closed.

    Amounts carry forward, so a month that only inherits its value would change whenever an
    earlier month is edited. An archived line plans nothing in an open month; writing that
    down as 0 keeps it at 0 after the month is closed, rather than letting the value it had
    before it was archived reappear.
    """
    rows = await _amount_rows(session)
    for line in (await session.scalars(select(BudgetLine))).all():
        history = rows.get(line.id, [])
        if any(m == month for m, _ in history):
            if not line.active:
                await session.execute(
                    delete(Budget).where(Budget.line_id == line.id).where(Budget.month == month)
                )
                session.add(Budget(line_id=line.id, month=month, amount=ZERO))
            continue
        amount, _ = _effective(history, month)
        if not line.active:
            amount = ZERO
        if amount or history:
            session.add(Budget(line_id=line.id, month=month, amount=amount))
    await session.flush()


# --- plan amounts ----------------------------------------------------------------


async def _amount_rows(session: AsyncSession) -> dict[uuid.UUID, list[tuple[date, Decimal]]]:
    rows: dict[uuid.UUID, list[tuple[date, Decimal]]] = defaultdict(list)
    for line_id, month, amount in (
        await session.execute(
            select(Budget.line_id, Budget.month, Budget.amount).order_by(Budget.month)
        )
    ).all():
        rows[line_id].append((month, Decimal(amount)))
    return rows


def _effective(history: list[tuple[date, Decimal]], month: date) -> tuple[Decimal, bool]:
    """The amount in force in `month`, and whether it was set in that very month."""
    amount, explicit = ZERO, False
    for set_in, value in history:
        if set_in > month:
            break
        amount, explicit = value, set_in == month
    return amount, explicit


def line_plan(
    line: BudgetLine,
    history: list[tuple[date, Decimal]],
    month: date,
    locked: set[date],
) -> tuple[Decimal, bool]:
    if month not in locked and not line.active:
        return ZERO, False
    return _effective(history, month)


async def set_amount(
    session: AsyncSession, line: BudgetLine, month: date, amount: Decimal | None
) -> None:
    """Set a line's amount from `month` on. None removes the change, inheriting again."""
    month = first_of(month)
    if month in await locked_months(session):
        raise BudgetError(
            f"{month_name(month)} le van zárva. Nyisd újra az időszakát, ha javítani kell."
        )
    if amount is not None and amount < 0:
        raise BudgetError("A keret nem lehet negatív.")
    existing = await session.scalar(
        select(Budget).where(Budget.line_id == line.id).where(Budget.month == month)
    )
    if amount is None:
        if existing is not None:
            await session.delete(existing)
    elif existing is not None:
        existing.amount = _q(amount)
    else:
        session.add(Budget(line_id=line.id, month=month, amount=_q(amount)))
    await session.flush()


