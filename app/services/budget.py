async def check_line(
    session: AsyncSession,
    *,
    line_id: uuid.UUID | None,
    owner_id: uuid.UUID | None,
    kind: str,
    category_ids: list[uuid.UUID],
    pocket_id: uuid.UUID | None = None,
    is_wishlist: bool = False,
) -> None:
    """A category may be in only one active line per owner, or spending would be ambiguous.

    Money set aside - a goal, savings, the wishlist's pot - always lives in a pocket (D25).
    Each owner has at most one wishlist pot, so a wishlist purchase knows where to draw from.
    """
    if kind not in {k.value for k in BudgetLineKind}:
        raise BudgetError("Ismeretlen csoport.")
    if owner_id is not None and await session.get(User, owner_id) is None:
        raise BudgetError("Nincs ilyen felhasználó.")
    if pocket_id is not None and await session.get(Pocket, pocket_id) is None:
        raise BudgetError("Nincs ilyen zseb.")
    if (kind not in SPENDING_KINDS or is_wishlist) and pocket_id is None:
        raise BudgetError("A félretett pénz egy zsebben van: válaszd ki, melyikben.")
    if kind in SPENDING_KINDS and not category_ids and pocket_id is None:
        raise BudgetError("Egy fix vagy változó keretnek legalább egy kategória kell.")
    if is_wishlist:
        clash = await session.scalar(
            select(BudgetLine.name)
            .where(BudgetLine.is_wishlist.is_(True))
            .where(BudgetLine.active.is_(True))
            .where(
                BudgetLine.owner_id == owner_id if owner_id is not None
                else BudgetLine.owner_id.is_(None)
            )
            .where(BudgetLine.id != line_id if line_id is not None else true())
        )
        if clash is not None:
            raise BudgetError(f"Ennek a gazdának már van kívánságlista-gyűjtése: {clash}.")
    if not category_ids:
        return
    known = {
        c.id: c.name
        for c in (
            await session.scalars(select(Category).where(Category.id.in_(category_ids)))
        ).all()
    }
    if len(known) != len(set(category_ids)):
        raise BudgetError("Nincs ilyen kategória.")
    clash_stmt = (
        select(BudgetLine.name, BudgetLineCategory.category_id)
        .join(BudgetLineCategory, BudgetLineCategory.line_id == BudgetLine.id)
        .where(BudgetLine.active.is_(True))
        .where(BudgetLineCategory.category_id.in_(category_ids))
        .where(
            BudgetLine.owner_id == owner_id if owner_id is not None
            else BudgetLine.owner_id.is_(None)
        )
    )
    if line_id is not None:
        clash_stmt = clash_stmt.where(BudgetLine.id != line_id)
    clash = (await session.execute(clash_stmt)).first()
    if clash is not None:
        raise BudgetError(f"A(z) {known[clash[1]]} kategória már a(z) {clash[0]} sorban van.")


async def set_line_categories(
    session: AsyncSession, line: BudgetLine, category_ids: list[uuid.UUID]
) -> None:
    wanted = list(dict.fromkeys(category_ids))
    # A line created a moment ago has never had its categories loaded, and an async session
    # cannot load them implicitly on first touch.
    await session.refresh(line, attribute_names=["categories"])
    line.categories = [
        link for link in line.categories if link.category_id in wanted
    ] + [
        BudgetLineCategory(category_id=category_id)
        for category_id in wanted
        if category_id not in line.category_ids
    ]
    await session.flush()


async def remove_line(session: AsyncSession, line: BudgetLine) -> bool:
    """Delete a line, or archive it if a closed period already planned with it.

    Returns True when it was deleted, False when archived. A line that a discussed month
    was planned with is part of that month's record; deleting it would rewrite history.
    """
    last_close = await session.scalar(select(func.max(BudgetPeriod.closed_at)))
    if last_close is not None and line.created_at is not None and line.created_at <= last_close:
        line.active = False
        await session.flush()
        return False
    await session.delete(line)
    await session.flush()
    return True


