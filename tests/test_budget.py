"""Budgeting: periods, the plan, and where the money went against it.

The rules most worth defending are the ones that could quietly put a forint in the wrong
place without any screen looking broken:

- spending counts against the line of its category, *whose* line depends on the split, and a
  parent category's line covers its children;
- a bill generated by a Rendszeres item counts against its own row, never twice;
- discounts are spread so a receipt's lines add up to what was paid;
- an amount carries forward until changed, and a closed month never changes after the fact;
- a salary that has not arrived is not money you have.
"""

