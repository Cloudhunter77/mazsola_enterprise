def rule(**overrides) -> RecurringPayment:
    values = dict(
        name="Rezsi – villany", merchant_name="MVM", amount=Decimal("15000"),
        currency="HUF", cadence="monthly", day_of_month=10, payment_method="card",
        starts_on=date(2026, 9, 1), active=True, direction="expense", amount_mode="fixed",
    )
    values.update(overrides)
    return RecurringPayment(**values)


class TestRecurringRows:
    async def test_a_generated_bill_counts_against_its_own_row_only(self, session):
        utilities = await category(session, "Rezsi")
        await line(session, "Rezsi", None, [utilities], amount=30_000)
        session.add(rule(name="Netflix", merchant_name="Netflix", category_id=utilities.id,
                         day_of_month=5))
        span = await open_september(session)
        await materialise_due(session, today=date(2026, 9, 30))

        view = await budget.month_view(session, span, TODAY)
        assert actuals(view)[("Netflix", None)] == Decimal("15000.00")
        assert actuals(view)[("Rezsi", None)] == Decimal("0.00"), "never counted twice"

    async def test_a_variable_bill_waits_for_its_amount(self, session):
        balazs, petra = await person(session, "Balázs"), await person(session, "Petra")
        bill = rule(amount_mode="variable", payer_id=balazs.id, default_shares=[
            {"user_id": str(balazs.id), "percent": "50"},
            {"user_id": str(petra.id), "percent": "50"},
        ])
        session.add(bill)
        await session.flush()
        assert await materialise_due(session, today=date(2026, 9, 30)) == []

        await confirm_occurrence(
            session, bill, date(2026, 9, 1), Decimal("17320"), date(2026, 9, 12), TODAY
        )
        charge = await session.scalar(select(RecurringCharge))
        booked = await session.get(Receipt, charge.receipt_id)
        assert booked.total_gross == Decimal("17320.00")
        assert booked.paid_by_id == balazs.id, "the rule's payer, so Elszámolás sees it"

        # From now on the plan expects what it came to last time.
        grid = await budget.plan_grid(session, date(2026, 10, 1), 1)
        assert grid.rows[0].amounts[0][0] == Decimal("17320.00")

    async def test_income_never_books_itself(self, session):
        balazs = await person(session, "Balázs")
        salary = rule(name="Fizetés", direction="income", owner_id=balazs.id,
                      amount=Decimal("600000"))
        session.add(salary)
        await session.flush()
        assert await materialise_due(session, today=date(2026, 9, 30)) == []
        assert await session.scalar(select(func.count(Receipt.id))) == 0, "income is no receipt"

        found = await occurrences_between(session, date(2026, 9, 1), date(2026, 10, 1), TODAY)
        assert [o.status for o in found] == ["due"]

        await confirm_occurrence(
            session, salary, date(2026, 9, 1), Decimal("598000"), date(2026, 9, 10), TODAY
        )
        entry = await session.scalar(select(IncomeEntry))
        assert entry.user_id == balazs.id and entry.amount == Decimal("598000.00")
        found = await occurrences_between(session, date(2026, 9, 1), date(2026, 10, 1), TODAY)
        assert [(o.status, o.amount) for o in found] == [("done", Decimal("598000.00"))]

    async def test_a_skipped_month_can_be_taken_back(self, session):
        salary = rule(name="Fizetés", direction="income")
        session.add(salary)
        await session.flush()
        await skip_occurrence(session, salary, date(2026, 9, 1))
        found = await occurrences_between(session, date(2026, 9, 1), date(2026, 10, 1), TODAY)
        assert found[0].status == "skipped"

        await undo_occurrence(session, salary, date(2026, 9, 1))
        found = await occurrences_between(session, date(2026, 9, 1), date(2026, 10, 1), TODAY)
        assert found[0].status == "due"

    async def test_undoing_a_confirmation_removes_what_it_created(self, session):
        bill = rule(amount_mode="variable")
        session.add(bill)
        await session.flush()
        await confirm_occurrence(
            session, bill, date(2026, 9, 1), Decimal("9000"), date(2026, 9, 10), TODAY
        )
        await undo_occurrence(session, bill, date(2026, 9, 1))
        assert await session.scalar(select(func.count(Receipt.id))) == 0
        assert await session.scalar(select(func.count(RecurringCharge.id))) == 0

    async def test_a_fixed_bill_that_booked_itself_is_not_undone_here(self, session):
        bill = rule()
        session.add(bill)
        await session.flush()
        await materialise_due(session, today=date(2026, 9, 30))
        with pytest.raises(OccurrenceError):
            await undo_occurrence(session, bill, date(2026, 9, 1))

    async def test_a_month_cannot_be_confirmed_twice(self, session):
        bill = rule(amount_mode="variable")
        session.add(bill)
        await session.flush()
        await confirm_occurrence(
            session, bill, date(2026, 9, 1), Decimal("9000"), date(2026, 9, 10), TODAY
        )
        with pytest.raises(OccurrenceError):
            await confirm_occurrence(
                session, bill, date(2026, 9, 1), Decimal("9000"), date(2026, 9, 10), TODAY
            )

    async def test_a_yearly_bill_is_planned_at_a_twelfth(self, session):
        session.add(rule(name="Biztosítás", cadence="yearly", month_of_year=3,
                         amount=Decimal("120000")))
