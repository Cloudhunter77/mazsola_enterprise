class TestPeriods:
    async def test_a_meeting_is_due_until_one_plans_this_month(self, session):
        assert budget.meeting_due([], TODAY), "before any meeting there is one to hold"

        await budget.open_period(
            session, starts_on=date(2026, 10, 2), month=None, user_id=None, today=TODAY
        )
        spans = await budget.periods(session)
        assert spans[-1].period.month == date(2026, 10, 1)
        # November has begun and nobody has planned it.
        assert budget.meeting_due(spans, TODAY)
        assert not budget.meeting_due(spans, date(2026, 10, 31))

        await budget.open_period(
            session, starts_on=date(2026, 11, 3), month=None, user_id=None, today=TODAY
        )
        assert not budget.meeting_due(await budget.periods(session), TODAY)

    def test_a_late_meeting_plans_the_next_month(self):
        assert budget.suggested_month(date(2026, 11, 2), None) == date(2026, 11, 1)
        assert budget.suggested_month(date(2026, 10, 29), None) == date(2026, 11, 1)

    def test_it_never_suggests_a_month_already_planned(self):
        previous = type("P", (), {"month": date(2026, 11, 1)})()
        assert budget.suggested_month(date(2026, 11, 20), previous) == date(2026, 12, 1)

    async def test_opening_a_period_closes_the_one_before(self, session):
        first = await open_september(session)
        await budget.open_period(
            session, starts_on=date(2026, 10, 3), month=None, user_id=None, today=TODAY
        )
        spans = await budget.periods(session)
        assert first.period.closed_at is not None
        # The first ends exactly where the second begins: no gap, no overlap.
        assert spans[0].end == date(2026, 10, 3) == spans[1].start
        assert spans[1].is_current

    @pytest.mark.parametrize(
        ("starts_on", "month", "why"),
        [
            (date(2026, 9, 1), None, "before the running period started"),
            (date(2026, 10, 3), date(2026, 9, 1), "planning a month already planned"),
            (date(2026, 11, 30), None, "a meeting in the future"),
        ],
    )
    async def test_an_impossible_period_is_refused(self, session, starts_on, month, why):
        await open_september(session)
        with pytest.raises(budget.BudgetError):
            await budget.open_period(
                session, starts_on=starts_on, month=month, user_id=None, today=TODAY
            )

    async def test_receipts_belong_to_a_period_by_their_date(self, session):
        food = await category(session, "Élelmiszer")
        await line(session, "Kaja", None, [food], amount=100_000)
        await open_september(session)
        await budget.open_period(
            session, starts_on=date(2026, 10, 3), month=None, user_id=None, today=TODAY
        )
        await receipt(session, date(2026, 10, 2), [(1000, food)])  # the day before the meeting
        await receipt(session, date(2026, 10, 3), [(2000, food)])  # the meeting day itself
        spans = await budget.periods(session)

        september = await budget.month_view(session, spans[0], TODAY)
        october = await budget.month_view(session, spans[1], TODAY)
        assert actuals(september)[("Kaja", None)] == Decimal("1000.00")
        assert actuals(october)[("Kaja", None)] == Decimal("2000.00")

    async def test_a_receipt_entered_after_the_meeting_is_flagged(self, session):
        food = await category(session, "Élelmiszer")
        await open_september(session)
        await receipt(session, date(2026, 9, 20), [(1500, food)])
        await budget.open_period(
            session, starts_on=date(2026, 10, 3), month=None, user_id=None, today=TODAY
        )
        await session.commit()
        # Entered after September was closed, but dated inside it.
        late = await receipt(session, date(2026, 9, 28), [(800, food)])
        await session.commit()

        spans = await budget.periods(session)
        october = await budget.month_view(session, spans[1], TODAY)
        assert [r.id for r, _ in october.late] == [late.id], "the next meeting sees it"
        september = await budget.month_view(session, spans[0], TODAY)
        assert [r.id for r, _ in september.late] == [late.id]


