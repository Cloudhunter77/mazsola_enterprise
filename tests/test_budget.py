class TestPlanAmounts:
    async def test_an_amount_carries_forward_until_changed(self, session):
        food = await category(session, "Élelmiszer")
        kaja = await line(session, "Kaja", None, [food], amount=100_000,
                          month=date(2026, 10, 1))
        await budget.set_amount(session, kaja, date(2026, 12, 1), Decimal("120000"))

        grid = await budget.plan_grid(session, date(2026, 9, 1), 6)
        row = next(r for r in grid.rows if r.id == kaja.id)
        assert [a for a, _ in row.amounts] == [
            Decimal("0"), Decimal("100000.00"), Decimal("100000.00"),
            Decimal("120000.00"), Decimal("120000.00"), Decimal("120000.00"),
        ]
        assert [e for _, e in row.amounts] == [False, True, False, True, False, False]

    async def test_removing_a_change_inherits_again(self, session):
        food = await category(session, "Élelmiszer")
        kaja = await line(session, "Kaja", None, [food], amount=100_000)
        await budget.set_amount(session, kaja, date(2026, 10, 1), Decimal("50000"))
        await budget.set_amount(session, kaja, date(2026, 10, 1), None)
        grid = await budget.plan_grid(session, date(2026, 10, 1), 1)
        assert grid.rows[0].amounts == [(Decimal("100000.00"), False)]

    async def test_a_closed_month_cannot_be_edited_until_reopened(self, session):
        food = await category(session, "Élelmiszer")
        kaja = await line(session, "Kaja", None, [food], amount=100_000)
        september = await open_september(session)
        await budget.open_period(
            session, starts_on=date(2026, 10, 3), month=None, user_id=None, today=TODAY
        )
        with pytest.raises(budget.BudgetError):
            await budget.set_amount(session, kaja, date(2026, 9, 1), Decimal("1"))

        await budget.reopen_period(session, september.period)
        await budget.set_amount(session, kaja, date(2026, 9, 1), Decimal("90000"))

    async def test_editing_an_earlier_month_does_not_change_a_closed_one(self, session):
        food = await category(session, "Élelmiszer")
        kaja = await line(session, "Kaja", None, [food], amount=100_000,
                          month=date(2026, 8, 1))
        await open_september(session)
        await budget.open_period(
            session, starts_on=date(2026, 10, 3), month=None, user_id=None, today=TODAY
        )
        # September inherited its 100 000 from August. Changing August now must not reach it.
        await budget.set_amount(session, kaja, date(2026, 8, 1), Decimal("70000"))
        grid = await budget.plan_grid(session, date(2026, 9, 1), 1)
        assert grid.rows[0].amounts[0][0] == Decimal("100000.00")

    async def test_a_negative_amount_is_refused(self, session):
        food = await category(session, "Élelmiszer")
        kaja = await line(session, "Kaja", None, [food])
        with pytest.raises(budget.BudgetError):
            await budget.set_amount(session, kaja, date(2026, 9, 1), Decimal("-1"))


