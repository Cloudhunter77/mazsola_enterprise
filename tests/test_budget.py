class TestBudgetApi:
    async def test_the_first_meeting_starts_budgeting(self, auth_client):
        status = (await auth_client.get("/api/budget/status")).json()
        assert status["meeting_due"] is True and status["current"] is None
        assert (await auth_client.get("/api/budget/month")).status_code == 404

        opened = await auth_client.post("/api/budget/periods", json={})
