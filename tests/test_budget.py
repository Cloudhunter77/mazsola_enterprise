# --- builders ---------------------------------------------------------------------


async def person(session, name: str) -> User:
    user = User(username=name.lower(), display_name=name, password_hash="x")
    session.add(user)
    await session.flush()
    return user


async def category(session, name: str, parent: Category | None = None) -> Category:
    row = Category(name=name, slug=f"{name.lower()}-{uuid.uuid4().hex[:6]}",
                   parent_id=parent.id if parent else None)
    session.add(row)
    await session.flush()
    return row


async def receipt(
    session,
    day: date,
    lines: list[tuple[float, Category | None]],
    *,
    total: float | None = None,
    paid_by: User | None = None,
    shares: list[tuple[User, int]] | None = None,
    merchant: str = "Lidl",
    discount: float | None = None,
) -> Receipt:
    items = [
        {"raw_name": f"tétel {i}", "gross_amount": amount,
         "category_id": cat.id if cat else None}
        for i, (amount, cat) in enumerate(lines, start=1)
    ]
    if discount:
        items.append({"raw_name": "KEDVEZMÉNY", "gross_amount": -discount, "kind": "discount"})
    stored = await create_manual_receipt(
        session,
        merchant_name=merchant,
        purchased_at=datetime.combine(day, time(12, 0), tzinfo=LOCAL_TZ),
        items=items,
        total_gross=total,
    )
    if paid_by is not None or shares:
        await set_split(
            session, stored, paid_by.id if paid_by else None,
            [(user.id, Decimal(pct)) for user, pct in shares or []],
        )
    await session.flush()
    return stored


async def line(
    session,
    name: str,
    owner: User | None,
    categories: list[Category],
    *,
    kind: str = "valtozo",
    amount: float | None = None,
    month: date = date(2026, 9, 1),
):
    from app.models import BudgetLine

    row = BudgetLine(name=name, owner_id=owner.id if owner else None, kind=kind, active=True)
    session.add(row)
    await session.flush()
    await budget.set_line_categories(session, row, [c.id for c in categories])
    if amount is not None:
        await budget.set_amount(session, row, month, Decimal(str(amount)))
    return row


def actuals(view: budget.MonthView) -> dict[tuple[str, uuid.UUID | None], Decimal | None]:
    return {(row.name, row.owner_id): row.actual for row in view.rows}


async def open_september(session) -> budget.PeriodSpan:
    await budget.open_period(
        session, starts_on=date(2026, 9, 2), month=None, user_id=None, today=TODAY
    )
    spans = await budget.periods(session)
    return spans[-1]


